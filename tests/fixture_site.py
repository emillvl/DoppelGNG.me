"""Owned HTTP fixture for routes, assets, JSON, downloads, and disclosures."""
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import base64
import hashlib
import json
from urllib.parse import urlsplit


SITE_CSS = b'@import "theme.css";body{margin:0;background:#f6f3eb;color:#172522;font:18px Georgia}main{max-width:700px;margin:auto;padding:24px}a{display:block;margin:18px 0}.spacer{height:900px;background:url(../art.svg) no-repeat center bottom}button,summary{cursor:pointer}'
STYLE_INTEGRITY = 'sha384-' + base64.b64encode(hashlib.sha384(SITE_CSS).digest()).decode('ascii')

PAGES = {
    '/': ('Archive', '<p id="status">Loading catalogue…</p><a href="/nested">Read the field guide</a><a href="/download.bin">Download dataset</a><details><summary>Collection notes</summary><p>Items are listed by year.</p></details><button type="button" id="menu" aria-expanded="false" aria-controls="panel">Open menu</button><div id="panel" hidden>Archive menu</div>'),
    '/nested/': ('Field guide', '<a href="/">Back to archive</a><p>The nested route can also be refreshed directly.</p><img src="image.svg" alt="Archive illustration" width="160" height="100">'),
    '/dynamic/': ('Dynamic catalogue', '<a href="/">Home</a><p>Discovered from a link generated by JavaScript.</p>'),
    '/menu-only/': ('Expanded menu route', '<a href="/">Home</a><p>This route is linked only after a disclosure interaction.</p>'),
}
SCRIPT = '''
const status = document.querySelector('#status');
if(status) fetch('/data.json?v=1').then(r=>r.json()).then(d=>status.textContent=d.label);
if(status){const a=document.createElement('a');a.href='/dynamic/';a.textContent='Dynamic catalogue';document.querySelector('main').append(a);}
const menu=document.querySelector('#menu');
if(menu) menu.addEventListener('click',()=>{const p=document.querySelector('#panel');p.hidden=!p.hidden;menu.setAttribute('aria-expanded',String(!p.hidden));if(!p.querySelector('a')){const a=document.createElement('a');a.href='/menu-only/';a.textContent='Expanded menu route';p.append(a);}});
const resourceParts=["/computed/", "/payload.js"];
const runtimeScript=document.createElement('script');runtimeScript.src=resourceParts[0]+"version-1"+resourceParts[1];document.head.append(runtimeScript);
'''


class Handler(BaseHTTPRequestHandler):
    def do_HEAD(self):
        if urlsplit(self.path).path == '/download.bin':
            self.send_response(405)
            self.send_header('Allow', 'GET')
            self.send_header('Content-Length', '0')
            self.end_headers()
            return
        self.serve(True)

    def do_GET(self):
        self.serve(False)

    def serve(self, head):
        route = urlsplit(self.path).path
        if route == '/nested':
            self.send_response(302)
            self.send_header('Location', '/nested/')
            self.send_header('Content-Length', '0')
            self.end_headers()
            return
        status = 200
        if route in PAGES:
            title, content = PAGES[route]
            body = f'<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>{title}</title><link rel="icon" href="/art.svg"><link rel="stylesheet" href="/css/site.css" integrity="{STYLE_INTEGRITY}"><script src="/app.js" defer></script></head><body><main><h1>{title}</h1>{content}<div class="spacer"></div><a href="#top" id="top">Top</a></main></body></html>'.encode()
            mime = 'text/html; charset=utf-8'
        elif route == '/app.js':
            body, mime = SCRIPT.encode(), 'application/javascript'
        elif route == '/computed/version-1/payload.js':
            body, mime = b'document.documentElement.dataset.computedAsset="loaded";', 'application/javascript'
        elif route == '/css/site.css':
            body, mime = SITE_CSS, 'text/css'
        elif route == '/css/theme.css':
            body, mime = b'h1{font-size:clamp(30px,7vw,64px)}details{padding:12px;border:1px solid #999}button{padding:10px}', 'text/css'
        elif route in ('/art.svg', '/nested/image.svg'):
            body, mime = b'<svg xmlns="http://www.w3.org/2000/svg" width="160" height="100"><rect width="160" height="100" fill="#c66942"/><circle cx="80" cy="50" r="32" fill="#efdeb9"/></svg>', 'image/svg+xml'
        elif route == '/data.json':
            body, mime = json.dumps({'label': 'Catalogue loaded: 24 records'}).encode(), 'application/json'
        elif route == '/download.bin':
            body, mime = b'owned-regression-dataset\x00\x01\x02', 'application/octet-stream'
        elif route == '/robots.txt':
            body = b'User-agent: *\nDisallow: /\n' if getattr(self.server, 'disallow_all', False) else b'User-agent: *\nDisallow: /private/\n'
            mime = 'text/plain'
        else:
            status, body, mime = 404, b'Not found', 'text/plain'
        self.send_response(status)
        self.send_header('Content-Type', mime)
        self.send_header('Content-Length', str(len(body)))
        self.end_headers()
        if not head:
            self.wfile.write(body)

    def log_message(self, *_):
        pass


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('--port', type=int, default=4318)
    parser.add_argument('--disallow-all', action='store_true', help='Disallow all routes in robots.txt for crawl-option regression checks')
    args = parser.parse_args()
    server = ThreadingHTTPServer(('127.0.0.1', args.port), Handler)
    server.disallow_all = args.disallow_all
    print(f'Owned regression fixture: http://127.0.0.1:{args.port}', flush=True)
    server.serve_forever()
